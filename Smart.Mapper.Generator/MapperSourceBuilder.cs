namespace Smart.Mapper.Generator;

using System;
using System.Collections.Generic;
using System.Globalization;
using System.Linq;
using System.Text;

using Microsoft.CodeAnalysis;

using Smart.Mapper.Generator.Helpers;
using Smart.Mapper.Generator.Models;

using SourceGenerateHelper;

internal static class MapperSourceBuilder
{
    internal static readonly string[] ReflectionPatterns =
    [
        "Activator.",
        "Type.GetType",
        "Assembly.Load",
        "MethodInfo",
        "PropertyInfo",
        "FieldInfo",
        "RuntimeHelpers.GetUninitializedObject",
        "MakeGenericType",
        "MakeGenericMethod"
    ];

    // Names the generated code declares start with __, which SMP0004 keeps out of mapper parameter
    // names, so they cannot collide with a parameter.
    private const string DestinationVariableName = "__d";
    private const string ExpressionFunctionPrefix = "__expression";
    private const string ConstructorArgumentPrefix = "__arg";
    private const string InitializerValuePrefix = "__init";

    internal static void BuildSource(SourceBuilder builder, EquatableArray<MapperMethodModel> methods)
    {
        var ns = methods[0].Namespace;
        var typeDeclarations = methods[0].TypeDeclarations;

        builder.AutoGenerated();
        builder.EnableNullable();
        builder.NewLine();

        if (!String.IsNullOrEmpty(ns))
        {
            builder.Namespace(IdentifierHelper.EscapeNames(ns));
            builder.NewLine();
        }

        // The containing types are declared again, outermost first, and the methods and the fields they use go
        // into the innermost
        foreach (var declaration in typeDeclarations)
        {
            builder.Indent().Append("partial ").Append(declaration).NewLine();
            builder.BeginScope();
        }

        var usedCultures = new HashSet<string>(StringComparer.Ordinal);
        foreach (var method in methods)
        {
            foreach (var mapping in method.PropertyMappings)
            {
                if (!String.IsNullOrEmpty(mapping.EffectiveCulture))
                {
                    usedCultures.Add(mapping.EffectiveCulture!);
                }
            }
        }

        if (usedCultures.Count > 0)
        {
            foreach (var culture in usedCultures.OrderBy(static c => c, StringComparer.Ordinal))
            {
                var fieldName = GetCultureFieldName(culture);
                builder.Indent()
                       .Append("private static readonly global::System.Globalization.CultureInfo ")
                       .Append(fieldName)
                       .Append(" = global::System.Globalization.CultureInfo.GetCultureInfo(")
                       .Append(ConstantExpressionHelper.FormatString(culture))
                       .Append(");")
                       .NewLine();
            }
            builder.NewLine();
        }

        var first = true;
        foreach (var method in methods)
        {
            if (first)
            {
                first = false;
            }
            else
            {
                builder.NewLine();
            }

            BuildMethod(builder, method);
        }

        for (var i = 0; i < typeDeclarations.Count; i++)
        {
            builder.EndScope();
        }
    }

    // A culture name (SMP0404 keeps it to letters and digits separated by hyphens and one underscore) as the
    // name of its field: a hyphen becomes an underscore and an underscore two, so that different names never
    // meet in one field (de-DE and de_DE).
    internal static string GetCultureFieldName(string cultureName) =>
        "__culture_" + cultureName.Replace("_", "__").Replace('-', '_');

    // Emits the parameter list with the modifiers and nullable annotations of the defining declaration,
    // which the implementation of a partial method has to repeat: this for extension mappers, and the
    // others (in, ref readonly, ref, scoped, params) as declared. The local functions computing
    // [MapExpression] values take the same list without this, which a local function cannot have, and
    // take a nullable source or destination as not null, as the method has checked it before the calls.
    private static void AppendParameters(SourceBuilder builder, MapperMethodModel method, bool forImplementation)
    {
        if (forImplementation && method.IsExtensionMethod)
        {
            builder.Append("this ");
        }

        AppendParameter(
            builder,
            method.SourceParameterModifiers,
            forImplementation ? method.SourceDeclaredTypeName : method.SourceNonNullableTypeName,
            method.SourceParameterName);

        if (!method.ReturnsDestination)
        {
            builder.Append(", ");
            AppendParameter(
                builder,
                method.DestinationParameterModifiers,
                forImplementation ? method.DestinationDeclaredTypeName : method.DestinationNonNullableTypeName,
                method.DestinationParameterName!);
        }

        foreach (var customParam in method.CustomParameters)
        {
            builder.Append(", ");
            AppendParameter(builder, customParam.Modifiers, customParam.DeclaredTypeName, customParam.Name);
        }
    }

    private static void AppendParameter(SourceBuilder builder, string modifiers, string typeName, string name)
    {
        if (modifiers.Length > 0)
        {
            builder.Append(modifiers).Append(" ");
        }

        builder.Append(typeName).Append(" ").Append(name);
    }

    // How a variable is passed to a parameter taking it with the given modifier: with ref for ref, and
    // with in for in and ref readonly (a ref readonly argument without it warns, CS9192). It serves the
    // local functions of [MapExpression], which take each mapper parameter with its own modifier, and the
    // methods the generated code calls, which the model matched only when their modifiers could take
    // the arguments.
    private static string GetArgumentModifier(RefKind refKind) => refKind switch
    {
        RefKind.Ref => "ref ",
        RefKind.In or RefKind.RefReadOnlyParameter => "in ",
        _ => string.Empty
    };

    // The modifier for passing a variable (a mapper parameter, __d, an element the loop reads, or the
    // instance created for an element mapper) as the argument at index of a called method. The property
    // value a converter, condition or nested mapper takes first is never passed through here: only by
    // value or in is allowed for it, and a value goes to in without a modifier.
    private static string GetCallArgumentModifier(EquatableArray<RefKind> parameterRefKinds, int index) =>
        index < parameterRefKinds.Count ? GetArgumentModifier(parameterRefKinds[index]) : string.Empty;

    internal static void BuildMethod(SourceBuilder builder, MapperMethodModel method)
    {
        // Mappers that emit collection loops have large bodies; forcing them into callers bloats
        // code for no gain, so AggressiveInlining is applied only to loop-free mappers.
        // (The helper path is a single converter call and stays inlinable.)
        var emitsLoop = method.MapCollectionMappings.Any(mc => mc.InPlace || !mc.UseHelperPath);
        if (!emitsLoop)
        {
            builder.Indent()
                   .Append("[global::System.Runtime.CompilerServices.MethodImpl(global::System.Runtime.CompilerServices.MethodImplOptions.AggressiveInlining)]")
                   .NewLine();
        }

        builder.Indent().Append(method.MethodAccessibility.ToText()).Append(" static partial ");
        builder.Append(method.ReturnsDestination ? method.DestinationDeclaredTypeName : "void").Append(" ");
        builder.Append(IdentifierHelper.Escape(method.MethodName)).Append(method.TypeParameterList).Append("(");
        AppendParameters(builder, method, forImplementation: true);
        builder.Append(")").Append(method.ConstraintClauses).NewLine();

        builder.BeginScope();

        AppendNullParameterCheck(builder, method);

        var destVarName = method.ReturnsDestination ? DestinationVariableName : method.DestinationParameterName!;

        if (method.ReturnsDestination)
        {
            if (method.UseConstructorMapping)
            {
                // The init-only and required members are assigned in the object initializer, the property
                // mappings first and then the explicit feature mappings (constant/expression/using/from) in
                // their order; the post-construction loops below skip them. A dotted path that only an
                // initializer can reach creates the members it goes through there.
                var initializerEntries = new List<InitializerEntry>();
                foreach (var pm in method.PropertyMappings.Where(static pm => (pm.IsTargetInitOnly || pm.IsTargetRequired) && !pm.IsConstructorParameter))
                {
                    initializerEntries.Add(new InitializerEntry(
                        pm.TargetPath,
                        pm.TargetPathSegments,
                        b => AppendPropertyValue(b, pm, method.SourceParameterName, method, nullChecked: false)));
                }

                // A required member the dotted paths write into after construction is created here, as it has
                // to be set in the object initializer
                foreach (var creation in method.RequiredMemberCreations)
                {
                    initializerEntries.Add(new InitializerEntry(creation.Path, default, b => b.Append("new ").Append(creation.TypeName).Append("()")));
                }

                var featureInitEntries = new List<(int Order, int DefinitionOrder, InitializerEntry Entry)>();
                foreach (var constant in method.ConstantMappings.Where(static c => (c.IsTargetInitOnly || c.IsTargetRequired) && !c.IsConstructorArgument))
                {
                    var value = constant.Value ?? "null";
                    featureInitEntries.Add((constant.Order, constant.DefinitionOrder, new InitializerEntry(constant.TargetName, constant.TargetPathSegments, b => b.Append(value))));
                }
                for (var i = 0; i < method.ExpressionMappings.Count; i++)
                {
                    var expression = method.ExpressionMappings[i];
                    if ((expression.IsTargetInitOnly || expression.IsTargetRequired) && !expression.IsConstructorArgument)
                    {
                        var value = BuildExpressionValue(method, i);
                        featureInitEntries.Add((expression.Order, expression.DefinitionOrder, new InitializerEntry(expression.TargetName, expression.TargetPathSegments, b => b.Append(value))));
                    }
                }
                foreach (var mapUsing in method.MapUsingMappings.Where(static mu => (mu.IsTargetInitOnly || mu.IsTargetRequired) && !mu.IsConstructorArgument))
                {
                    var value = BuildMapUsingCall(mapUsing, method);
                    featureInitEntries.Add((mapUsing.Order, mapUsing.DefinitionOrder, new InitializerEntry(mapUsing.TargetName, mapUsing.TargetPathSegments, b => b.Append(value))));
                }
                foreach (var mapFrom in method.MapFromMappings.Where(static mf => (mf.IsTargetInitOnly || mf.IsTargetRequired) && !mf.IsConstructorArgument))
                {
                    var value = BuildMapFromValue(mapFrom, method);
                    featureInitEntries.Add((mapFrom.Order, mapFrom.DefinitionOrder, new InitializerEntry(mapFrom.TargetName, default, b => b.Append(value))));
                }

                initializerEntries.AddRange(featureInitEntries.OrderBy(static x => x.Order).ThenBy(static x => x.DefinitionOrder).Select(static x => x.Entry));

                var ctorParameters = method.ConstructorParameters;
                var arguments = EmitConstructorArgumentLocals(builder, method);
                initializerEntries.AddRange(EmitInitializerLocals(builder, method));
                builder.Indent().Append("var ").Append(destVarName).Append(" = new ").Append(method.DestinationTypeName).Append("(");
                for (var i = 0; i < ctorParameters.Count; i++)
                {
                    if (i > 0)
                    {
                        builder.Append(", ");
                    }

                    // An argument after an optional parameter left out goes by name
                    if (ctorParameters[i].IsNamed)
                    {
                        builder.Append(IdentifierHelper.Escape(ctorParameters[i].ParamName)).Append(": ");
                    }

                    AppendConstructorArgument(builder, method, ctorParameters[i].TargetPath, ctorParameters[i].Kind, arguments);
                }
                builder.Append(")");

                if (initializerEntries.Count > 0)
                {
                    builder.NewLine();
                    builder.Indent().Append("{").NewLine();
                    builder.IndentLevel++;
                    EmitInitializerEntries(builder, initializerEntries, 0);
                    builder.IndentLevel--;
                    builder.Indent().Append("}");
                }

                builder.Append(";").NewLine();
            }
            else
            {
                builder.Indent().Append("var ").Append(destVarName).Append(" = new ").Append(method.DestinationTypeName).Append("();").NewLine();
            }
        }

        if (!String.IsNullOrEmpty(method.BeforeMapMethod))
        {
            AppendCallbackCall(builder, method, method.BeforeMapMethod!, method.BeforeMapParameterRefKinds, method.BeforeMapAcceptsCustomParameters, destVarName);
        }

        // Feature mappings already emitted in the object initializer are skipped here.
        bool EmittedInInitializer(bool isTargetInitOnly, bool isTargetRequired) =>
            method.UseConstructorMapping && (isTargetInitOnly || isTargetRequired);

        // The intermediate members of the target paths are created up front, up to the first one the
        // mapper cannot assign and create; the assignments through that one write into what it holds (see
        // EmitTargetAssignments). A mapping with a nullable source path creates them under its null check, and one
        // whose assignment is under a check of its own (IsAssignmentGuarded) right before it assigns, so that a
        // target left as it is does not get members created either. A required member the object initializer
        // created is not created again.
        var createdInInitializer = new HashSet<string>(method.RequiredMemberCreations.Select(static c => c.Path), StringComparer.Ordinal);
        var nestedPathsToInstantiate = new Dictionary<string, string>(StringComparer.Ordinal);
        void AddCreatedPaths(EquatableArray<NestedPathSegment> segments)
        {
            foreach (var segment in segments.TakeWhile(static s => s.Access == TargetSegmentAccess.Create))
            {
                if (!createdInInitializer.Contains(segment.Path) && !nestedPathsToInstantiate.ContainsKey(segment.Path))
                {
                    nestedPathsToInstantiate[segment.Path] = segment.TypeName;
                }
            }
        }

        foreach (var mapping in method.PropertyMappings)
        {
            if (mapping.SourcePathSegments.Any(s => s.IsNullable) || mapping.IsAssignmentGuarded() ||
                (!mapping.IsConstructorParameter && EmittedInInitializer(mapping.IsTargetInitOnly, mapping.IsTargetRequired)))
            {
                continue;
            }

            AddCreatedPaths(mapping.TargetPathSegments);
        }

        foreach (var constant in method.ConstantMappings.Where(c => !EmittedInInitializer(c.IsTargetInitOnly, c.IsTargetRequired)))
        {
            AddCreatedPaths(constant.TargetPathSegments);
        }

        foreach (var expression in method.ExpressionMappings.Where(e => !EmittedInInitializer(e.IsTargetInitOnly, e.IsTargetRequired)))
        {
            AddCreatedPaths(expression.TargetPathSegments);
        }

        foreach (var mapUsing in method.MapUsingMappings.Where(u => !EmittedInInitializer(u.IsTargetInitOnly, u.IsTargetRequired)))
        {
            AddCreatedPaths(mapUsing.TargetPathSegments);
        }

        foreach (var kvp in nestedPathsToInstantiate.OrderBy(x => x.Key.Count(c => c == '.')))
        {
            AppendInstantiation(builder, destVarName, kvp.Key, kvp.Value);
        }

        var createdUpFront = new HashSet<string>(createdInInitializer.Concat(nestedPathsToInstantiate.Keys), StringComparer.Ordinal);

        var effectiveMappings = method.UseConstructorMapping
            ? method.PropertyMappings.Where(m => !m.IsTargetInitOnly && !m.IsTargetRequired && !m.IsConstructorParameter).ToList()
            : method.PropertyMappings.ToList();
        var sortedMappings = effectiveMappings.OrderBy(m => m.Order).ThenBy(m => m.DefinitionOrder).ToList();
        var mappingsWithoutNullCheck = sortedMappings.Where(m => !m.RequiresNullCheck()).ToList();
        var mappingsWithNullCheck = sortedMappings.Where(m => m.RequiresNullCheck()).ToList();

        BuildPropertyAssignments(builder, mappingsWithoutNullCheck, method, destVarName, nullChecked: false, createdUpFront);

        var groupedByNullCheck = mappingsWithNullCheck
            .GroupBy(m => GetNullCheckCondition(m, method.SourceParameterName))
            .Where(g => !String.IsNullOrEmpty(g.Key));

        // The intermediate members the target paths of the mappings go through, created under their null check, of
        // those whose assignment is not under a check of its own, which creates them when it assigns; the members
        // created up front, the ones created here included
        HashSet<string> AppendGroupInstantiations(IEnumerable<PropertyMappingModel> mappings)
        {
            var groupNestedPaths = new Dictionary<string, string>(StringComparer.Ordinal);
            foreach (var mapping in mappings.Where(static m => !m.IsAssignmentGuarded()))
            {
                foreach (var segment in mapping.TargetPathSegments.TakeWhile(static s => s.Access == TargetSegmentAccess.Create))
                {
                    if (!createdInInitializer.Contains(segment.Path) && !groupNestedPaths.ContainsKey(segment.Path))
                    {
                        groupNestedPaths[segment.Path] = segment.TypeName;
                    }
                }
            }

            foreach (var kvp in groupNestedPaths.OrderBy(x => x.Key.Count(c => c == '.')))
            {
                AppendInstantiation(builder, destVarName, kvp.Key, kvp.Value);
            }

            return new HashSet<string>(createdUpFront.Concat(groupNestedPaths.Keys), StringComparer.Ordinal);
        }

        foreach (var group in groupedByNullCheck)
        {
            builder.Indent().Append("if (").Append(group.Key).Append(")").NewLine();
            builder.BeginScope();
            var createdInGroup = AppendGroupInstantiations(group);
            BuildPropertyAssignments(builder, group, method, destVarName, nullChecked: true, createdInGroup);
            builder.EndScope();

            // A mapping with NullValue takes it when an intermediate member of its source path is null, as it
            // does for a null value; the others, NullBehavior.Skip and one a condition guards, which has no value
            // to take, leave their targets as they are
            var substituted = group.Where(static m => m.HasNullValue() && (m.NullBehavior != NullBehaviorType.Skip) && !m.HasCondition()).ToList();
            if (substituted.Count > 0)
            {
                builder.Indent().Append("else").NewLine();
                builder.BeginScope();
                var createdInElse = AppendGroupInstantiations(substituted);
                EmitTargetAssignments(
                    builder,
                    destVarName,
                    substituted.Select(m => new TargetAssignment(m.TargetPathSegments, m.TargetPath, (target, _) => AppendAssignment(builder, target, m.NullValue!))),
                    createdInElse);
                builder.EndScope();
            }
        }

        EmitTargetAssignments(
            builder,
            destVarName,
            method.ConstantMappings
                .Where(c => !c.IsConstructorArgument && !EmittedInInitializer(c.IsTargetInitOnly, c.IsTargetRequired))
                .OrderBy(static c => c.Order)
                .ThenBy(static c => c.DefinitionOrder)
                .Select(c => new TargetAssignment(c.TargetPathSegments, c.TargetName, (target, _) => AppendAssignment(builder, target, c.Value ?? "null"))),
            createdUpFront);

        EmitTargetAssignments(
            builder,
            destVarName,
            method.ExpressionMappings
                .Select(static (e, index) => (Expression: e, Index: index))
                .Where(x => !x.Expression.IsConstructorArgument && !EmittedInInitializer(x.Expression.IsTargetInitOnly, x.Expression.IsTargetRequired))
                .OrderBy(static x => x.Expression.Order)
                .ThenBy(static x => x.Expression.DefinitionOrder)
                .Select(x => new TargetAssignment(x.Expression.TargetPathSegments, x.Expression.TargetName, (target, _) => AppendAssignment(builder, target, BuildExpressionValue(method, x.Index)))),
            createdUpFront);

        EmitTargetAssignments(
            builder,
            destVarName,
            method.MapUsingMappings
                .Where(u => !u.IsConstructorArgument && !EmittedInInitializer(u.IsTargetInitOnly, u.IsTargetRequired))
                .OrderBy(static u => u.Order)
                .ThenBy(static u => u.DefinitionOrder)
                .Select(u => new TargetAssignment(u.TargetPathSegments, u.TargetName, (target, _) => AppendAssignment(builder, target, BuildMapUsingCall(u, method)))),
            createdUpFront);

        EmitTargetAssignments(
            builder,
            destVarName,
            method.MapFromMappings
                .Where(f => !f.IsConstructorArgument && !EmittedInInitializer(f.IsTargetInitOnly, f.IsTargetRequired))
                .OrderBy(static f => f.Order)
                .ThenBy(static f => f.DefinitionOrder)
                .Select(f => new TargetAssignment(default, f.TargetName, (target, _) => AppendMapFromAssignment(builder, target, f, method))),
            createdUpFront);

        foreach (var mapNested in method.MapNestedMappings.Where(static m => !m.IsConstructorArgument && !m.IsInitializerEntry).OrderBy(m => m.Order).ThenBy(m => m.DefinitionOrder))
        {
            EmitNestedMapping(builder, mapNested, method, $"{destVarName}.{IdentifierHelper.EscapePath(mapNested.TargetName)}");
        }

        var collectionConverterTypeName = method.CollectionConverterTypeName ?? Names.QualifiedDefaultCollectionConverter;
        foreach (var mapCollection in method.MapCollectionMappings.Where(static m => !m.IsConstructorArgument && !m.IsInitializerEntry).OrderBy(m => m.Order).ThenBy(m => m.DefinitionOrder))
        {
            EmitCollectionMapping(builder, mapCollection, method, $"{destVarName}.{IdentifierHelper.EscapePath(mapCollection.TargetName)}", collectionConverterTypeName);
        }

        if (!String.IsNullOrEmpty(method.AfterMapMethod))
        {
            AppendCallbackCall(builder, method, method.AfterMapMethod!, method.AfterMapParameterRefKinds, method.AfterMapAcceptsCustomParameters, destVarName);
        }

        if (method.ReturnsDestination)
        {
            builder.Indent().Append("return ").Append(destVarName).Append(";").NewLine();
        }

        EmitExpressionFunctions(builder, method);

        builder.EndScope();
    }

    // A source or destination declared nullable is read or written below. When it is null there is
    // nothing to map, so before anything happens (BeforeMap, creating the instance) a return-type mapper
    // returns default and a void mapper returns, leaving the destination as it is. Past the check the
    // compiler takes both as not null.
    private static void AppendNullParameterCheck(SourceBuilder builder, MapperMethodModel method)
    {
        if (!method.IsSourceParameterNullable && !method.IsDestinationParameterNullable)
        {
            return;
        }

        builder.Indent().Append("if (");
        if (method.IsSourceParameterNullable)
        {
            builder.Append(method.SourceParameterName).Append(" is null");
        }

        if (method.IsDestinationParameterNullable)
        {
            builder.Append(method.IsSourceParameterNullable ? " || " : string.Empty).Append(method.DestinationParameterName!).Append(" is null");
        }

        builder.Append(")").NewLine();
        builder.BeginScope();
        if (method.ReturnsDestination)
        {
            builder.Indent().Append("return ").Append(method.DefaultReturnValue).Append(";").NewLine();
        }
        else
        {
            builder.Indent().Append("return;").NewLine();
        }
        builder.EndScope();
    }

    // The init-only and required members [MapNested] and [MapCollection] assign are made before construction into
    // locals the object initializer sets, as the arguments of the constructor are, the nested members first, each in
    // their order.
    private static List<InitializerEntry> EmitInitializerLocals(SourceBuilder builder, MapperMethodModel method)
    {
        var entries = new List<InitializerEntry>();
        var collectionConverterTypeName = method.CollectionConverterTypeName ?? Names.QualifiedDefaultCollectionConverter;
        foreach (var mapNested in method.MapNestedMappings.Where(static m => m.IsInitializerEntry).OrderBy(static m => m.Order).ThenBy(static m => m.DefinitionOrder))
        {
            var local = InitializerValuePrefix + entries.Count.ToString(CultureInfo.InvariantCulture);
            builder.Indent().Append(mapNested.ArgumentLocalType).Append(" ").Append(local).Append(";").NewLine();
            EmitNestedMapping(builder, mapNested, method, local);
            entries.Add(new InitializerEntry(mapNested.TargetName, default, b => b.Append(local)));
        }

        foreach (var mapCollection in method.MapCollectionMappings.Where(static m => m.IsInitializerEntry).OrderBy(static m => m.Order).ThenBy(static m => m.DefinitionOrder))
        {
            var local = InitializerValuePrefix + entries.Count.ToString(CultureInfo.InvariantCulture);
            builder.Indent().Append(mapCollection.TargetType).Append(" ").Append(local).Append(";").NewLine();
            EmitCollectionMapping(builder, mapCollection, method, local, collectionConverterTypeName);
            entries.Add(new InitializerEntry(mapCollection.TargetName, default, b => b.Append(local)));
        }

        return entries;
    }

    // The arguments of the constructor that [MapNested] and [MapCollection] supply are made before
    // construction into locals the call passes, as their mappings take statements (a void mapper filling an
    // instance, a loop filling a collection).
    private static Dictionary<string, string> EmitConstructorArgumentLocals(SourceBuilder builder, MapperMethodModel method)
    {
        var locals = new Dictionary<string, string>(StringComparer.Ordinal);
        var collectionConverterTypeName = method.CollectionConverterTypeName ?? Names.QualifiedDefaultCollectionConverter;
        for (var i = 0; i < method.ConstructorParameters.Count; i++)
        {
            var (_, target, kind, _) = method.ConstructorParameters[i];
            var local = ConstructorArgumentPrefix + i.ToString(CultureInfo.InvariantCulture);
            if (kind == ConstructorArgumentKind.MapNested)
            {
                var mapNested = method.MapNestedMappings.First(n => n.TargetName == target);
                builder.Indent().Append(mapNested.ArgumentLocalType).Append(" ").Append(local).Append(";").NewLine();
                EmitNestedMapping(builder, mapNested, method, local);
                locals[target] = local;
            }
            else if (kind == ConstructorArgumentKind.MapCollection)
            {
                var mapCollection = method.MapCollectionMappings.First(c => c.TargetName == target);
                builder.Indent().Append(mapCollection.TargetType).Append(" ").Append(local).Append(";").NewLine();
                EmitCollectionMapping(builder, mapCollection, method, local, collectionConverterTypeName);
                locals[target] = local;
            }
        }

        return locals;
    }

    // An argument of the constructor: the value of the property mapping or of the attribute that assigns the
    // member the parameter assigns, or the local made for it before construction.
    private static void AppendConstructorArgument(SourceBuilder builder, MapperMethodModel method, string target, ConstructorArgumentKind kind, Dictionary<string, string> locals)
    {
        switch (kind)
        {
            case ConstructorArgumentKind.Constant:
                builder.Append(method.ConstantMappings.First(c => c.TargetName == target).Value ?? "null");
                break;
            case ConstructorArgumentKind.Expression:
                for (var i = 0; i < method.ExpressionMappings.Count; i++)
                {
                    if (method.ExpressionMappings[i].TargetName == target)
                    {
                        builder.Append(BuildExpressionValue(method, i));
                        break;
                    }
                }

                break;
            case ConstructorArgumentKind.MapUsing:
                builder.Append(BuildMapUsingCall(method.MapUsingMappings.First(u => u.TargetName == target), method));
                break;
            case ConstructorArgumentKind.MapFrom:
                builder.Append(BuildMapFromValue(method.MapFromMappings.First(f => f.TargetName == target), method));
                break;
            case ConstructorArgumentKind.MapNested:
            case ConstructorArgumentKind.MapCollection:
                builder.Append(locals[target]);
                break;
            default:
                // BuildConstructorParameterMappings guarantees a mapping exists for every argument; First is
                // deliberate so a broken invariant fails the build loudly instead of emitting an empty argument.
                AppendPropertyValue(builder, method.PropertyMappings.First(pm => pm.TargetPath == target), method.SourceParameterName, method, nullChecked: false);
                break;
        }
    }

    // [MapNested]: the mapper called with the source member, a void one filling an instance created for it,
    // and the result assigned to the target (a member of the destination, or the local of a constructor
    // argument). A null source member gives default, and a nullable struct one the mapper takes the value of
    // goes to it as that value.
    private static void EmitNestedMapping(SourceBuilder builder, MapNestedModel mapNested, MapperMethodModel method, string targetAccess)
    {
        var sourceAccess = $"{method.SourceParameterName}.{IdentifierHelper.EscapePath(mapNested.SourceName)}";
        var mapper = IdentifierHelper.Escape(mapNested.Mapper);
        var sourceArgument = mapNested.UnwrapsSource ? sourceAccess + ".Value" : mapNested.IsSourceNullable ? sourceAccess + "!" : sourceAccess;

        if (mapNested.MapperReturnsValue)
        {
            builder.Indent();
            builder.Append(targetAccess).Append(" = ");
            if (mapNested.IsSourceNullable)
            {
                builder.Append(sourceAccess).Append(" is not null ? ");
            }
            builder.Append(mapper).Append("(").Append(sourceArgument).Append(")");
            if (mapNested.ForgivesMapperResult)
            {
                builder.Append("!");
            }
            if (mapNested.IsSourceNullable)
            {
                builder.Append(" : ").Append(mapNested.NullResult);
            }
            builder.Append(";").NewLine();
            return;
        }

        // The property value goes as is; the instance created for the mapper is a local, passed the way the
        // mapper takes it
        var nestedVarName = "__nested_" + mapNested.TargetName.Replace(".", "_");
        var instanceModifier = GetCallArgumentModifier(mapNested.MapperParameterRefKinds, 1);
        if (mapNested.IsSourceNullable)
        {
            builder.Indent().Append("if (").Append(sourceAccess).Append(" is not null)").NewLine();
            builder.BeginScope();
            builder.Indent().Append("var ").Append(nestedVarName).Append(" = new ").Append(mapNested.TargetType).Append("();").NewLine();
            builder.Indent().Append(mapper).Append("(").Append(sourceArgument).Append(", ").Append(instanceModifier).Append(nestedVarName).Append(");").NewLine();
            builder.Indent().Append(targetAccess).Append(" = ").Append(nestedVarName).Append(";").NewLine();
            builder.EndScope();
            builder.Indent().Append("else").NewLine();
            builder.BeginScope();
            builder.Indent().Append(targetAccess).Append(" = default!;").NewLine();
            builder.EndScope();
        }
        else
        {
            builder.Indent().Append("var ").Append(nestedVarName).Append(" = new ").Append(mapNested.TargetType).Append("();").NewLine();
            builder.Indent().Append(mapper).Append("(").Append(sourceAccess).Append(", ").Append(instanceModifier).Append(nestedVarName).Append(");").NewLine();
            builder.Indent().Append(targetAccess).Append(" = ").Append(nestedVarName).Append(";").NewLine();
        }
    }

    // BeforeMap / AfterMap: the source, the destination and the custom parameters, each passed the way
    // the callback's parameter takes it.
    private static void AppendCallbackCall(
        SourceBuilder builder,
        MapperMethodModel method,
        string callback,
        EquatableArray<RefKind> parameterRefKinds,
        bool acceptsCustomParameters,
        string destVarName)
    {
        builder.Indent().Append(IdentifierHelper.Escape(callback)).Append("(")
            .Append(GetCallArgumentModifier(parameterRefKinds, 0)).Append(method.SourceParameterName).Append(", ")
            .Append(GetCallArgumentModifier(parameterRefKinds, 1)).Append(destVarName);
        if (acceptsCustomParameters)
        {
            AppendCustomArguments(builder, method, parameterRefKinds, 2);
        }
        builder.Append(");").NewLine();
    }

    // A nullable reference the method returns into a target not annotated as nullable is taken with !, as [MapFrom]
    // takes it.
    private static string BuildMapUsingCall(MapUsingModel mapUsing, MapperMethodModel method)
    {
        var call = new StringBuilder(IdentifierHelper.Escape(mapUsing.Method));
        call.Append('(').Append(GetCallArgumentModifier(mapUsing.ParameterRefKinds, 0)).Append(method.SourceParameterName);
        if (mapUsing.AcceptsCustomParameters)
        {
            for (var i = 0; i < method.CustomParameters.Count; i++)
            {
                call.Append(", ").Append(GetCallArgumentModifier(mapUsing.ParameterRefKinds, i + 1)).Append(method.CustomParameters[i].Name);
            }
        }
        call.Append(')');
        if (mapUsing.ForgivesNull)
        {
            call.Append('!');
        }

        return call.ToString();
    }

    // [MapFrom]: a parameterless method of the source called, or a property path of it read, a nullable reference
    // going to a target not annotated as one taken with !, as a property mapping takes it. Read through members that
    // may be null, the value is an expression that gives null to a target taking it, or default, when one is null.
    private static string BuildMapFromValue(MapFromModel mapFrom, MapperMethodModel method)
    {
        var value = BuildMapFromRead(mapFrom, method);
        var condition = GetMapFromNullCheckCondition(mapFrom, method);
        return condition.Length == 0 ? value : $"{condition} ? {value} : {(mapFrom.IsTargetNullable ? "null" : "default!")}";
    }

    // [MapFrom] in a statement: read through members that may be null, the target is assigned under their null check
    // and left as it is when one is null, as for the source path of a property mapping.
    private static void AppendMapFromAssignment(SourceBuilder builder, string target, MapFromModel mapFrom, MapperMethodModel method)
    {
        var condition = GetMapFromNullCheckCondition(mapFrom, method);
        if (condition.Length == 0)
        {
            AppendAssignment(builder, target, BuildMapFromRead(mapFrom, method));
            return;
        }

        builder.Indent().Append("if (").Append(condition).Append(")").NewLine();
        builder.BeginScope();
        AppendAssignment(builder, target, BuildMapFromRead(mapFrom, method));
        builder.EndScope();
    }

    private static string BuildMapFromRead(MapFromModel mapFrom, MapperMethodModel method) =>
        (mapFrom.IsMethodCall
            ? $"{method.SourceParameterName}.{IdentifierHelper.Escape(mapFrom.Member)}()"
            : $"{method.SourceParameterName}.{IdentifierHelper.EscapePath(mapFrom.Member)}") +
        (mapFrom.ForgivesNull ? "!" : string.Empty);

    private static string GetMapFromNullCheckCondition(MapFromModel mapFrom, MapperMethodModel method) =>
        String.Join(" && ", mapFrom.NullCheckedPaths.Select(path => $"{method.SourceParameterName}.{IdentifierHelper.EscapePath(path)} is not null"));

    private static void AppendAssignment(SourceBuilder builder, string target, string value) =>
        builder.Indent().Append(target).Append(" = ").Append(value).Append(";").NewLine();

    // The custom parameters as the arguments following the first ones of a called method.
    private static void AppendCustomArguments(SourceBuilder builder, MapperMethodModel method, EquatableArray<RefKind> parameterRefKinds, int firstIndex)
    {
        for (var i = 0; i < method.CustomParameters.Count; i++)
        {
            builder.Append(", ").Append(GetCallArgumentModifier(parameterRefKinds, firstIndex + i)).Append(method.CustomParameters[i].Name);
        }
    }

    private static string GetExpressionFunctionName(int index) =>
        ExpressionFunctionPrefix + index.ToString(CultureInfo.InvariantCulture);

    // The value assigned for the [MapExpression] at the given index: a call to its local function (see
    // EmitExpressionFunctions). An unresolved target gives no type to declare that function with, so its
    // expression stays inline and the compiler reports the missing member there, as it did before.
    private static string BuildExpressionValue(MapperMethodModel method, int index)
    {
        var expression = method.ExpressionMappings[index];
        if (expression.TargetType is null)
        {
            return expression.Expression;
        }

        var call = new StringBuilder(GetExpressionFunctionName(index));
        call.Append('(').Append(GetArgumentModifier(method.SourceRefKind)).Append(method.SourceParameterName);
        if (!method.ReturnsDestination)
        {
            call.Append(", ").Append(GetArgumentModifier(method.DestinationRefKind)).Append(method.DestinationParameterName);
        }

        foreach (var customParam in method.CustomParameters)
        {
            call.Append(", ").Append(GetArgumentModifier(customParam.RefKind)).Append(customParam.Name);
        }

        return call.Append(')').ToString();
    }

    // Each [MapExpression] becomes a static local function at the end of the method that takes the
    // mapper's parameters under the same names. Variables the expression declares (out var, patterns)
    // stay inside that function instead of colliding in the method body, and being static, it can take
    // in parameters and ref structs, which a capturing one could not. It returns the target member's
    // type, so the expression converts to the target as it would in a direct assignment.
    internal static void EmitExpressionFunctions(SourceBuilder builder, MapperMethodModel method)
    {
        var separated = false;
        var annotationsDisabled = false;
        for (var i = 0; i < method.ExpressionMappings.Count; i++)
        {
            var expression = method.ExpressionMappings[i];
            if (expression.TargetType is null)
            {
                continue;
            }

            if (!separated)
            {
                builder.NewLine();
                separated = true;
            }

            // A target declared with annotations disabled has an oblivious type. Spelled with the
            // annotations of this file it would read as non-nullable, and a null result would warn where
            // the direct assignment did not.
            if (expression.IsTargetTypeOblivious != annotationsDisabled)
            {
                annotationsDisabled = expression.IsTargetTypeOblivious;
                builder.Append(annotationsDisabled ? "#nullable disable annotations" : "#nullable enable annotations").NewLine();
            }

            builder.Indent().Append("static ").Append(expression.TargetType).Append(" ").Append(GetExpressionFunctionName(i)).Append("(");
            AppendParameters(builder, method, forImplementation: false);
            builder.Append(") => ").Append(expression.Expression).Append(";").NewLine();
        }

        if (annotationsDisabled)
        {
            builder.Append("#nullable enable annotations").NewLine();
        }
    }

    // Target is what the collection is assigned to, as the generated code reaches it: a member of the
    // destination, or the local of a constructor argument.
    internal static void EmitCollectionMapping(
        SourceBuilder builder,
        MapCollectionModel mapCollection,
        MapperMethodModel method,
        string target,
        string collectionConverterTypeName)
    {
        if (mapCollection.InPlace)
        {
            EmitInPlaceCollectionMapping(builder, mapCollection, method, target);
            return;
        }

        if (mapCollection.UseHelperPath)
        {
            EmitHelperCollectionMapping(builder, mapCollection, method, target, collectionConverterTypeName);
            return;
        }

        EmitInlineCollectionMapping(builder, mapCollection, method, target);
    }

    internal static void EmitInPlaceCollectionMapping(
        SourceBuilder builder,
        MapCollectionModel mapCollection,
        MapperMethodModel method,
        string target)
    {
        var sourceAccess = $"{method.SourceParameterName}.{IdentifierHelper.EscapePath(mapCollection.SourceName)}";
        var destAccess = target;
        var fallbackType = mapCollection.InPlaceFallbackTypeName;

        if (mapCollection.IsSourceNullable)
        {
            builder.Indent().Append("if (").Append(sourceAccess).Append(" is not null)").NewLine();
        }

        // The iteration locals (__srcSpan, __dstColl, ...) have fixed names, so each mapping gets a block
        // of its own, as on the inline path.
        builder.BeginScope();

        // Known-count sources size the fallback instance so the first fill avoids growth
        // reallocations (List.Clear/HashSet.Clear preserve capacity on subsequent calls).
        var srcBang = mapCollection.IsSourceNullable ? "!" : string.Empty;
        var capacityArg = mapCollection.SourceShape switch
        {
            CollectionSourceShape.Array or CollectionSourceShape.ImmutableArray or
            CollectionSourceShape.ReadOnlyMemory or CollectionSourceShape.Memory => $"{sourceAccess}{srcBang}.Length",
            CollectionSourceShape.List or CollectionSourceShape.IndexedList or
            CollectionSourceShape.ReadOnlyCollection => $"{sourceAccess}{srcBang}.Count",
            _ => string.Empty
        };

        // A target the mapper can assign gets a new instance when it is null; List<T> and HashSet<T> take
        // the capacity, a collection class of its own is created without arguments. A target it cannot
        // assign is filled only when it holds an instance, and a null one is left as it is.
        if (fallbackType is not null)
        {
            var takesCapacity =
                fallbackType.StartsWith("global::System.Collections.Generic.List<", StringComparison.Ordinal) ||
                fallbackType.StartsWith("global::System.Collections.Generic.HashSet<", StringComparison.Ordinal);
            builder.Indent().Append("if (").Append(destAccess).Append(" is null)").NewLine();
            builder.BeginScope();
            builder.Indent().Append(destAccess).Append(" = new ").Append(fallbackType).Append("(").Append(takesCapacity ? capacityArg : string.Empty).Append(");").NewLine();
            builder.EndScope();
        }
        else
        {
            builder.Indent().Append("if (").Append(destAccess).Append(" is not null)").NewLine();
            builder.BeginScope();
        }

        // Direct member access on a concrete List<T>/HashSet<T> lets the JIT devirtualize and inline
        // Clear/Add; the ICollection<T> cast is required only for interface-typed destinations.
        var isConcreteTarget =
            mapCollection.TargetType.StartsWith("global::System.Collections.Generic.List<", StringComparison.Ordinal) ||
            mapCollection.TargetType.StartsWith("global::System.Collections.Generic.HashSet<", StringComparison.Ordinal);
        var iCollectionType = $"global::System.Collections.Generic.ICollection<{mapCollection.TargetElementTypeArgument}>";
        var collectionAccess = isConcreteTarget ? destAccess : $"(({iCollectionType}){destAccess})";
        builder.Indent().Append(collectionAccess).Append(".Clear();").NewLine();

        // A pre-existing destination may be undersized; growing once up front avoids repeated
        // reallocation during Add. EnsureCapacity is not on ICollection<T>, so this is emitted
        // only for concrete List/HashSet destinations.
        if (isConcreteTarget && (capacityArg.Length > 0))
        {
            builder.Indent().Append(collectionAccess).Append(".EnsureCapacity(").Append(capacityArg).Append(");").NewLine();
        }

        EmitInPlaceSourceIteration(builder, mapCollection, sourceAccess, collectionAccess);

        if (fallbackType is null)
        {
            builder.EndScope();
        }

        builder.EndScope();
    }

    internal static void EmitInPlaceSourceIteration(
        SourceBuilder builder,
        MapCollectionModel mapCollection,
        string sourceAccess,
        string collectionAccess)
    {
        var srcNullBang = mapCollection.IsSourceNullable ? "!" : string.Empty;

        switch (mapCollection.SourceShape)
        {
            case CollectionSourceShape.Array:
            {
                builder.Indent().Append("var __srcArr = ").Append(sourceAccess).Append(srcNullBang).Append(";").NewLine();
                builder.Indent().Append("var __dstColl = ").Append(collectionAccess).Append(";").NewLine();
                builder.Indent().Append("for (var __i = 0; __i < __srcArr.Length; __i++)").NewLine();
                builder.BeginScope();
                EmitInPlaceAddItem(builder, mapCollection, "__srcArr[__i]", "__dstColl");
                builder.EndScope();
                break;
            }
            case CollectionSourceShape.List:
            {
                builder.Indent().Append("var __srcSpan = global::System.Runtime.InteropServices.CollectionsMarshal.AsSpan(").Append(sourceAccess).Append(srcNullBang).Append(");").NewLine();
                builder.Indent().Append("var __dstColl = ").Append(collectionAccess).Append(";").NewLine();
                builder.Indent().Append("for (var __i = 0; __i < __srcSpan.Length; __i++)").NewLine();
                builder.BeginScope();
                EmitInPlaceAddItem(builder, mapCollection, "__srcSpan[__i]", "__dstColl");
                builder.EndScope();
                break;
            }
            case CollectionSourceShape.ImmutableArray:
            {
                builder.Indent().Append("var __srcSpan = ").Append(sourceAccess).Append(".AsSpan();").NewLine();
                builder.Indent().Append("var __dstColl = ").Append(collectionAccess).Append(";").NewLine();
                builder.Indent().Append("for (var __i = 0; __i < __srcSpan.Length; __i++)").NewLine();
                builder.BeginScope();
                EmitInPlaceAddItem(builder, mapCollection, "__srcSpan[__i]", "__dstColl");
                builder.EndScope();
                break;
            }
            case CollectionSourceShape.ReadOnlyMemory:
            case CollectionSourceShape.Memory:
            {
                builder.Indent().Append("var __srcSpan = ").Append(sourceAccess).Append(srcNullBang).Append(".Span;").NewLine();
                builder.Indent().Append("var __dstColl = ").Append(collectionAccess).Append(";").NewLine();
                builder.Indent().Append("for (var __i = 0; __i < __srcSpan.Length; __i++)").NewLine();
                builder.BeginScope();
                EmitInPlaceAddItem(builder, mapCollection, "__srcSpan[__i]", "__dstColl");
                builder.EndScope();
                break;
            }
            case CollectionSourceShape.IndexedList:
            {
                builder.Indent().Append("var __srcList = ").Append(sourceAccess).Append(srcNullBang).Append(";").NewLine();
                builder.Indent().Append("var __count = __srcList.Count;").NewLine();
                builder.Indent().Append("var __dstColl = ").Append(collectionAccess).Append(";").NewLine();
                builder.Indent().Append("for (var __i = 0; __i < __count; __i++)").NewLine();
                builder.BeginScope();
                EmitInPlaceAddItem(builder, mapCollection, "__srcList[__i]", "__dstColl");
                builder.EndScope();
                break;
            }
            default:
            {
                builder.Indent().Append("var __dstColl = ").Append(collectionAccess).Append(";").NewLine();
                builder.Indent().Append("foreach (var __item in ").Append(sourceAccess).Append(srcNullBang).Append(")").NewLine();
                builder.BeginScope();
                EmitInPlaceAddItem(builder, mapCollection, "__item", "__dstColl");
                builder.EndScope();
                break;
            }
        }
    }

    internal static void EmitInPlaceAddItem(
        SourceBuilder builder,
        MapCollectionModel mapCollection,
        string itemExpr,
        string dstCollExpr)
    {
        EmitElement(builder, mapCollection, itemExpr, value => $"{dstCollExpr}.Add({value});");
    }

    // Emits the mapping of an element: the element mapper called with it, and store writing the result, or the
    // instance a void mapper filled, into the target collection. A nullable struct element the mapper takes the
    // value of goes to it as that value, read once with a pattern, as the flow analysis does not follow an element
    // from its null check (CS8629), and a null one is stored as default.
    private static void EmitElement(SourceBuilder builder, MapCollectionModel mapCollection, string itemExpr, Func<string, string> store)
    {
        var mapper = GetElementMapper(mapCollection);
        if (mapCollection.MapperReturnsValue)
        {
            var call = mapCollection.UnwrapsSource
                ? $"{itemExpr} is {{ }} __value ? {mapper}(__value){GetElementResultSuffix(mapCollection)} : {mapCollection.NullResult}"
                : $"{mapper}({GetElementArgumentModifier(mapCollection)}{itemExpr}){GetElementResultSuffix(mapCollection)}";
            builder.Indent().Append(store(call)).NewLine();
            return;
        }

        if (mapCollection.UnwrapsSource)
        {
            builder.Indent().Append("if (").Append(itemExpr).Append(" is { } __value)").NewLine();
            builder.BeginScope();
        }

        var argument = mapCollection.UnwrapsSource ? "__value" : GetElementArgumentModifier(mapCollection) + itemExpr;
        builder.Indent().Append("var __dest = new ").Append(mapCollection.TargetElementType).Append("();").NewLine();
        builder.Indent().Append(mapper).Append("(").Append(argument).Append(", ").Append(GetInstanceArgumentModifier(mapCollection)).Append("__dest);").NewLine();
        builder.Indent().Append(store("__dest")).NewLine();

        if (mapCollection.UnwrapsSource)
        {
            builder.EndScope();
            builder.Indent().Append("else").NewLine();
            builder.BeginScope();
            builder.Indent().Append(store("default!")).NewLine();
            builder.EndScope();
        }
    }

    // The modifier the element goes to the element mapper with. The loops read it from an array, a span or
    // a foreach variable, all variables, except for IList<T> / IReadOnlyList<T>, whose indexer returns a
    // value, which goes as is.
    private static string GetElementArgumentModifier(MapCollectionModel mapCollection) =>
        mapCollection.SourceShape == CollectionSourceShape.IndexedList ? string.Empty : GetCallArgumentModifier(mapCollection.MapperParameterRefKinds, 0);

    private static string GetElementMapper(MapCollectionModel mapCollection) =>
        IdentifierHelper.Escape(mapCollection.Mapper!);

    // What follows the call of a value-returning element mapper: ! for one returning a nullable reference into
    // elements not annotated as one.
    private static string GetElementResultSuffix(MapCollectionModel mapCollection) =>
        mapCollection.ForgivesMapperResult ? "!" : string.Empty;

    // The modifier the instance created for a void element mapper goes with.
    private static string GetInstanceArgumentModifier(MapCollectionModel mapCollection) =>
        GetCallArgumentModifier(mapCollection.MapperParameterRefKinds, 1);

    // The element mapper goes to the converter method as a delegate, which the model matched only when
    // the mapper takes its parameters the way the delegate does.
    internal static void EmitHelperCollectionMapping(
        SourceBuilder builder,
        MapCollectionModel mapCollection,
        MapperMethodModel method,
        string target,
        string collectionConverterTypeName)
    {
        var sourceAccess = $"{method.SourceParameterName}.{IdentifierHelper.EscapePath(mapCollection.SourceName)}";
        builder.Indent();
        builder.Append(target).Append(" = ");
        builder.Append(collectionConverterTypeName).Append(".");

        builder.Append(mapCollection.HasCustomConverter()
            ? IdentifierHelper.Escape(mapCollection.Converter!)
            : mapCollection.TargetCollectionMethod);

        builder.Append("<")
               .Append(mapCollection.SourceElementTypeArgument)
               .Append(", ")
               .Append(mapCollection.TargetElementTypeArgument)
               .Append(">(");
        builder.Append(sourceAccess).Append(", ");
        builder.Append(GetElementMapper(mapCollection));
        builder.Append(")!");
        builder.Append(";").NewLine();
    }

    internal static void EmitInlineCollectionMapping(
        SourceBuilder builder,
        MapCollectionModel mapCollection,
        MapperMethodModel method,
        string target)
    {
        var sourceAccess = $"{method.SourceParameterName}.{IdentifierHelper.EscapePath(mapCollection.SourceName)}";
        var destProp = target;
        var dstElem = mapCollection.TargetElementTypeArgument;
        var srcNullBang = mapCollection.IsSourceNullable ? "!" : string.Empty;

        if (mapCollection.IsSourceNullable)
        {
            if (mapCollection.SourceShape == CollectionSourceShape.ImmutableArray)
            {
                builder.Indent().Append("if (").Append(sourceAccess).Append(".IsDefaultOrEmpty)").NewLine();
                builder.BeginScope();
                builder.Indent().Append(destProp).Append(" = default!;").NewLine();
                builder.EndScope();
                builder.Indent().Append("else").NewLine();
            }
            else
            {
                builder.Indent().Append("if (").Append(sourceAccess).Append(" is null)").NewLine();
                builder.BeginScope();
                builder.Indent().Append(destProp).Append(" = default!;").NewLine();
                builder.EndScope();
                builder.Indent().Append("else").NewLine();
            }
        }

        // The locals below (__src, __srcList, __count, __list, __dst, ...) have fixed names, so each
        // mapping declares them in a block of its own. Left at method scope, they would be redeclared by a
        // second mapping in the same mapper (CS0128) and clash with those of a nullable one under its else
        // (CS0136).
        builder.BeginScope();

        switch (mapCollection.SourceShape)
        {
            case CollectionSourceShape.Array:
                builder.Indent().Append("var __src = global::System.MemoryExtensions.AsSpan(").Append(sourceAccess).Append(srcNullBang).Append(");").NewLine();
                EmitInlineTargetBuild(builder, mapCollection, dstElem, destProp, "__src", "__src.Length");
                break;
            case CollectionSourceShape.List:
                builder.Indent().Append("var __src = global::System.Runtime.InteropServices.CollectionsMarshal.AsSpan(").Append(sourceAccess).Append(srcNullBang).Append(");").NewLine();
                EmitInlineTargetBuild(builder, mapCollection, dstElem, destProp, "__src", "__src.Length");
                break;
            case CollectionSourceShape.ImmutableArray:
                builder.Indent().Append("var __src = ").Append(sourceAccess).Append(".AsSpan();").NewLine();
                EmitInlineTargetBuild(builder, mapCollection, dstElem, destProp, "__src", "__src.Length");
                break;
            case CollectionSourceShape.ReadOnlyMemory:
            case CollectionSourceShape.Memory:
                builder.Indent().Append("var __src = ").Append(sourceAccess).Append(srcNullBang).Append(".Span;").NewLine();
                EmitInlineTargetBuild(builder, mapCollection, dstElem, destProp, "__src", "__src.Length");
                break;
            case CollectionSourceShape.IndexedList:
                // Count is hoisted into a local so the loop condition does not re-invoke the
                // interface Count getter on every iteration.
                builder.Indent().Append("var __srcList = ").Append(sourceAccess).Append(srcNullBang).Append(";").NewLine();
                builder.Indent().Append("var __count = __srcList.Count;").NewLine();
                EmitInlineTargetBuild(builder, mapCollection, dstElem, destProp, "__srcList", "__count");
                break;
            case CollectionSourceShape.ReadOnlyCollection:
                builder.Indent().Append("var __srcColl = ").Append(sourceAccess).Append(srcNullBang).Append(";").NewLine();
                EmitInlineTargetBuildFromCollection(builder, mapCollection, dstElem, destProp, "__srcColl", "__srcColl.Count");
                break;
            default:
                EmitInlineTargetBuildFromEnumerable(builder, mapCollection, dstElem, destProp, sourceAccess + srcNullBang);
                break;
        }

        builder.EndScope();
    }

    internal static void EmitInlineTargetBuild(
        SourceBuilder builder,
        MapCollectionModel mapCollection,
        string dstElem,
        string destProp,
        string srcSpanExpr,
        string lengthExpr)
    {
        switch (mapCollection.TargetShape)
        {
            case CollectionTargetShape.Array:
                builder.Indent().Append("var __arr = new ").Append(dstElem).Append("[").Append(lengthExpr).Append("];").NewLine();
                EmitIndexedLoop(builder, mapCollection, srcSpanExpr, lengthExpr, "__arr");
                builder.Indent().Append(destProp).Append(" = __arr;").NewLine();
                break;
            case CollectionTargetShape.List:
                builder.Indent().Append("var __list = new global::System.Collections.Generic.List<").Append(dstElem).Append(">(").Append(lengthExpr).Append(");").NewLine();
                builder.Indent().Append("global::System.Runtime.InteropServices.CollectionsMarshal.SetCount(__list, ").Append(lengthExpr).Append(");").NewLine();
                builder.Indent().Append("var __dst = global::System.Runtime.InteropServices.CollectionsMarshal.AsSpan(__list);").NewLine();
                EmitIndexedLoop(builder, mapCollection, srcSpanExpr, lengthExpr, "__dst");
                builder.Indent().Append(destProp).Append(" = __list;").NewLine();
                break;
            case CollectionTargetShape.ImmutableArray:
                builder.Indent().Append("var __ib = global::System.Collections.Immutable.ImmutableArray.CreateBuilder<").Append(dstElem).Append(">(").Append(lengthExpr).Append(");").NewLine();
                EmitIndexedLoopAdd(builder, mapCollection, srcSpanExpr, lengthExpr, "__ib");
                builder.Indent().Append(destProp).Append(" = __ib.MoveToImmutable();").NewLine();
                break;
            case CollectionTargetShape.ImmutableList:
                builder.Indent().Append("var __ib = global::System.Collections.Immutable.ImmutableList.CreateBuilder<").Append(dstElem).Append(">();").NewLine();
                EmitIndexedLoopAdd(builder, mapCollection, srcSpanExpr, lengthExpr, "__ib");
                builder.Indent().Append(destProp).Append(" = __ib.ToImmutable();").NewLine();
                break;
            case CollectionTargetShape.HashSet:
                builder.Indent().Append("var __set = new global::System.Collections.Generic.HashSet<").Append(dstElem).Append(">(").Append(lengthExpr).Append(");").NewLine();
                EmitIndexedLoopAdd(builder, mapCollection, srcSpanExpr, lengthExpr, "__set");
                builder.Indent().Append(destProp).Append(" = __set;").NewLine();
                break;
            case CollectionTargetShape.ImmutableHashSet:
                builder.Indent().Append("var __ib = global::System.Collections.Immutable.ImmutableHashSet.CreateBuilder<").Append(dstElem).Append(">();").NewLine();

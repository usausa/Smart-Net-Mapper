    // Emits the property mappings, each through the intermediate members of its target path, the members already
    // created (createdUpFront) aside.
    private static void BuildPropertyAssignments(
        SourceBuilder builder,
        IEnumerable<PropertyMappingModel> mappings,
        MapperMethodModel method,
        string destVarName,
        bool nullChecked,
        IReadOnlyCollection<string> createdUpFront)
    {
        EmitTargetAssignments(
            builder,
            destVarName,
            mappings.Select(m => new TargetAssignment(
                m.TargetPathSegments,
                m.TargetPath,
                (target, create) => BuildPropertyAssignment(builder, m, method.SourceParameterName, target, method, nullChecked, create),
                m.IsAssignmentGuarded())),
            createdUpFront);
    }

    // An assignment to a target path: the intermediate members it goes through, the path, and what writes
    // the assignment to the member at its end, given how that member is reached and what creates the intermediate
    // members of the path (null when none is left to create). One under a check of its own (Guarded) creates them
    // right before it assigns, under the check, and the others before it.
    private sealed record TargetAssignment(EquatableArray<NestedPathSegment> Segments, string Path, Action<string, Action?> Emit, bool Guarded = false);

    // A scope an assignment is written in: a null check of a member whose instance it writes into, or a
    // block that copies a struct property into a local and assigns it back at the end.
    private sealed record TargetScope(string Key, string Expression, string? CopyLocal);

    // Emits the assignments in order, each through the intermediate members of its target path. A member the
    // mapper creates is created with ??= when null; the leading ones are created up front (createdUpFront, see
    // BuildMethod), except for an assignment under a check of its own, which creates the members it goes through
    // right before it assigns, under the check, as long as nothing before created them. A member whose instance is
    // written into (one the mapper cannot assign, or of a type it cannot create) is null-checked, and nothing is
    // assigned through it when it is null. A struct property is a value, so it is copied into a local, written into,
    // and assigned back. Consecutive assignments through the same checks and copies share them.
    private static void EmitTargetAssignments(SourceBuilder builder, string destVarName, IEnumerable<TargetAssignment> assignments, IReadOnlyCollection<string> createdUpFront)
    {
        var scopes = new List<TargetScope>();
        var created = new List<HashSet<string>> { new(StringComparer.Ordinal) };
        foreach (var assignment in assignments)
        {
            // The scopes and creations along the path, and the member at its end as reached through them
            var steps = new List<(TargetScope? Scope, NestedPathSegment Segment, string Expression)>();
            var expression = destVarName;
            var leading = true;
            var copies = 0;
            foreach (var segment in assignment.Segments)
            {
                expression += "." + IdentifierHelper.Escape(GetLastName(segment.Path));
                switch (segment.Access)
                {
                    case TargetSegmentAccess.Create:
                        if (!leading || (assignment.Guarded && !createdUpFront.Contains(segment.Path)))
                        {
                            steps.Add((null, segment, expression));
                        }
                        break;
                    case TargetSegmentAccess.Existing:
                        steps.Add((new TargetScope(segment.Path, expression, null), segment, expression));
                        leading = false;
                        break;
                    case TargetSegmentAccess.Copy:
                        var local = "__copy" + copies++.ToString(CultureInfo.InvariantCulture);
                        steps.Add((new TargetScope(segment.Path, expression, local), segment, expression));
                        expression = local;
                        leading = false;
                        break;
                    default:
                        leading = false;
                        break;
                }
            }

            var required = steps.Select(static x => x.Scope).OfType<TargetScope>().ToList();
            var shared = 0;
            while ((shared < scopes.Count) && (shared < required.Count) && (scopes[shared] == required[shared]))
            {
                shared++;
            }

            CloseTargetScopes(builder, scopes, created, shared);

            var level = 0;
            var pending = new List<(string Expression, string TypeName)>();
            foreach (var (scope, segment, segmentExpression) in steps)
            {
                if (scope is null)
                {
                    if (assignment.Guarded)
                    {
                        if (!created[level].Contains(segment.Path))
                        {
                            pending.Add((segmentExpression, segment.TypeName));
                        }
                    }
                    else if (created[level].Add(segment.Path))
                    {
                        builder.Indent().Append(segmentExpression).Append(" ??= new ").Append(segment.TypeName).Append("();").NewLine();
                    }

                    continue;
                }

                level++;
                if (level <= shared)
                {
                    continue;
                }

                if (scope.CopyLocal is null)
                {
                    builder.Indent().Append("if (").Append(scope.Expression).Append(" is not null)").NewLine();
                    builder.BeginScope();
                }
                else
                {
                    builder.BeginScope();
                    builder.Indent().Append("var ").Append(scope.CopyLocal).Append(" = ").Append(scope.Expression).Append(";").NewLine();
                }

                scopes.Add(scope);
                created.Add([with(StringComparer.Ordinal)]);
            }

            var create = pending.Count == 0
                ? null
                : new Action(() =>
                {
                    foreach (var (pendingExpression, typeName) in pending)
                    {
                        builder.Indent().Append(pendingExpression).Append(" ??= new ").Append(typeName).Append("();").NewLine();
                    }
                });
            assignment.Emit(expression + "." + IdentifierHelper.Escape(GetLastName(assignment.Path)), create);
        }

        CloseTargetScopes(builder, scopes, created, 0);
    }

    // Closes the scopes past count, a copy assigning its local back first.
    private static void CloseTargetScopes(SourceBuilder builder, List<TargetScope> scopes, List<HashSet<string>> created, int count)
    {
        while (scopes.Count > count)
        {
            var scope = scopes[scopes.Count - 1];
            if (scope.CopyLocal is not null)
            {
                builder.Indent().Append(scope.Expression).Append(" = ").Append(scope.CopyLocal).Append(";").NewLine();
            }

            builder.EndScope();
            scopes.RemoveAt(scopes.Count - 1);
            created.RemoveAt(created.Count - 1);
        }
    }

    private static string GetLastName(string path)
    {
        var index = path.LastIndexOf('.');
        return index < 0 ? path : path.Substring(index + 1);
    }

    private static void AppendInstantiation(SourceBuilder builder, string destVarName, string path, string typeName) =>
        builder.Indent().Append(destVarName).Append(".").Append(IdentifierHelper.EscapePath(path)).Append(" ??= new ").Append(typeName).Append("();").NewLine();

    // An entry of the object initializer: the member path it assigns, the intermediate members the path goes
    // through, and what writes the value.
    private sealed record InitializerEntry(string Path, EquatableArray<NestedPathSegment> Segments, Action<SourceBuilder> AppendValue);

    // Emits the entries at the given depth of their paths, grouped by the member there in the order they
    // come: an entry ending at the member assigns it, and the ones going through it create it with an object
    // initializer of their own (a member reached only through the initializer: an init-only member at the
    // end of a dotted path).
    private static void EmitInitializerEntries(SourceBuilder builder, IEnumerable<InitializerEntry> entries, int depth)
    {
        foreach (var group in entries.GroupBy(e => e.Path.Split('.')[depth], StringComparer.Ordinal))
        {
            var name = IdentifierHelper.Escape(group.Key);
            var deeper = new List<InitializerEntry>();
            foreach (var entry in group)
            {
                if (entry.Path.Split('.').Length > depth + 1)
                {
                    deeper.Add(entry);
                    continue;
                }

                builder.Indent().Append(name).Append(" = ");
                entry.AppendValue(builder);
                builder.Append(",").NewLine();
            }

            if (deeper.Count > 0)
            {
                builder.Indent().Append(name).Append(" = new ").Append(deeper[0].Segments[depth].TypeName).Append("()").NewLine();
                builder.Indent().Append("{").NewLine();
                builder.IndentLevel++;
                EmitInitializerEntries(builder, deeper, depth + 1);
                builder.IndentLevel--;
                builder.Indent().Append("},").NewLine();
            }
        }
    }

    // Target is the member the mapping assigns, as the generated code reaches it (__d.Child.Value). Create writes what
    // creates the intermediate members of the target path, right before the assignment, under the checks it is
    // written in.
    internal static void BuildPropertyAssignment(
        SourceBuilder builder,
        PropertyMappingModel mapping,
        string sourceParamName,
        string target,
        MapperMethodModel method,
        bool nullChecked = false,
        Action? create = null)
    {
        if (mapping.HasCondition())
        {
            // A condition whose parameter does not take null is not met by a null source, which is not passed to it
            var sourceAccessor = BuildSourceAccessor(mapping.SourcePath, sourceParamName, nullChecked);
            builder.Indent().Append("if (");
            if (mapping.IsSourceNullable && mapping.ConditionRejectsNull)
            {
                builder.Append(sourceAccessor).Append(" is not null && ");
            }

            builder.Append(IdentifierHelper.Escape(mapping.ConditionMethod!)).Append("(").Append(sourceAccessor);
            if (mapping.ConditionUnwrapsSource)
            {
                builder.Append(".Value");
            }

            if (mapping.ConditionAcceptsCustomParameters)
            {
                AppendCustomArguments(builder, method, mapping.ConditionParameterRefKinds, 1);
            }
            builder.Append("))").NewLine();
            builder.BeginScope();
        }

        if (mapping.IsSourceNullable && !mapping.HasConverter() && !mapping.RequiresConversion &&
            (mapping.NullBehavior == NullBehaviorType.Skip))
        {
            BuildSkipAssignment(builder, mapping, sourceParamName, target, nullChecked, create);
        }
        else if (mapping.IsSourceNullable && mapping.RequiresConversion && !mapping.HasConverter())
        {
            BuildNullableSourceConversion(builder, mapping, sourceParamName, target, method, nullChecked, create);
        }
        else if (mapping.IsSourceNullable && mapping.HasConverter() &&
                 ((mapping.NullBehavior == NullBehaviorType.Skip) || (mapping.ConverterRejectsNull && !mapping.HasNullValue())))
        {
            // The converter takes the source as it is, so a null source leaves the destination as it is by
            // not calling it, with NullBehavior.Skip, and for a converter whose parameter does not take null and no
            // NullValue to give instead
            var sourceAccessor = BuildSourceAccessor(mapping.SourcePath, sourceParamName, nullChecked);
            builder.Indent().Append("if (").Append(sourceAccessor).Append(" is not null)").NewLine();
            builder.BeginScope();
            create?.Invoke();
            builder.Indent().Append(target).Append(" = ");
            AppendConverterCall(builder, mapping, sourceAccessor, method);
            builder.Append(";").NewLine();
            builder.EndScope();
        }
        else
        {
            BuildStandardAssignment(builder, mapping, sourceParamName, target, method, nullChecked, create);
        }

        if (mapping.HasCondition())
        {
            builder.EndScope();
        }
    }

    // Emits a guarded assignment for NullBehavior.Skip when no type conversion is required:
    // a nullable source is copied only when it has a value, otherwise the destination is left as-is.
    internal static void BuildSkipAssignment(SourceBuilder builder, PropertyMappingModel mapping, string sourceParamName, string target, bool nullChecked, Action? create = null)
    {
        var sourceAccessor = BuildSourceAccessor(mapping.SourcePath, sourceParamName, nullChecked);
        var isNullableValueType = mapping.SourceType.Contains("?") || mapping.SourceType.Contains("Nullable<");

        builder.Indent().Append("if (").Append(sourceAccessor).Append(" is not null)").NewLine();
        builder.BeginScope();
        create?.Invoke();
        builder.Indent().Append(target).Append(" = ").Append(sourceAccessor);
        if (!mapping.IsTargetNullable)
        {
            builder.Append(isNullableValueType ? ".GetValueOrDefault()" : "!");
        }
        builder.Append(";").NewLine();
        builder.EndScope();
    }

    internal static void BuildStandardAssignment(
        SourceBuilder builder,
        PropertyMappingModel mapping,
        string sourceParamName,
        string target,
        MapperMethodModel method,
        bool nullChecked,
        Action? create = null)
    {
        create?.Invoke();
        builder.Indent();
        builder.Append(target).Append(" = ");
        AppendPropertyValue(builder, mapping, sourceParamName, method, nullChecked);
        builder.Append(";").NewLine();
    }

    // Appends the right-hand side of a mapping as a single expression: converter call, type
    // conversion, or a plain accessor with null substitution / unwrapping.
    //
    // Constructor arguments and object-initializer entries reuse this so that they go through the
    // same conversion pipeline as ordinary property assignments. They cannot use the statement-based
    // paths (BuildSkipAssignment / BuildNullableSourceConversion), which is why the value has to be
    // expressible on its own.
    internal static void AppendPropertyValue(SourceBuilder builder, PropertyMappingModel mapping, string sourceParamName, MapperMethodModel method, bool nullChecked)
    {
        // Statement contexts guard nullable intermediate path segments with a grouped `if` and pass
        // nullChecked: true; expression contexts cannot, so the guard becomes a conditional here.
        // Without it a dotted source such as src.Child!.Val dereferences a null intermediate.
        if (!nullChecked && mapping.RequiresNullCheck())
        {
            builder.Append(GetNullCheckCondition(mapping, sourceParamName)).Append(" ? ");
            AppendPropertyValueCore(builder, mapping, sourceParamName, method, nullChecked: true);
            builder.Append(" : ");
            AppendNullFallback(builder, mapping);
            return;
        }

        AppendPropertyValueCore(builder, mapping, sourceParamName, method, nullChecked);
    }

    private static void AppendPropertyValueCore(SourceBuilder builder, PropertyMappingModel mapping, string sourceParamName, MapperMethodModel method, bool nullChecked)
    {
        if (!mapping.HasConverter() && mapping.IsSourceNullable && mapping.RequiresConversion)
        {
            AppendNullableSourceConversionValue(builder, mapping, sourceParamName, method, nullChecked);
            return;
        }

        if (mapping.HasConverter())
        {
            // The converter takes the source as it is; with NullValue, a null source takes NullValue instead, and
            // the converter is called for a value only. A converter whose parameter does not take null is called for
            // a value only as well, a null source giving null to a target taking it, or default
            var sourceAccessor = BuildSourceAccessor(mapping.SourcePath, sourceParamName, nullChecked);
            var substitutesNull = mapping.IsSourceNullable && (mapping.HasNullValue() || mapping.ConverterRejectsNull);
            if (substitutesNull)
            {
                builder.Append(sourceAccessor).Append(" is not null ? ");
            }

            AppendConverterCall(builder, mapping, sourceAccessor, method);

            if (substitutesNull)
            {
                builder.Append(" : ");
                AppendNullFallback(builder, mapping);
            }
        }
        else if (mapping.RequiresConversion)
        {
            BuildTypeConversion(builder, mapping, sourceParamName, nullChecked, method);
        }
        else
        {
            var sourceAccessor = BuildSourceAccessor(mapping.SourcePath, sourceParamName, nullChecked);
            builder.Append(sourceAccessor);

            if (mapping.HasNullValue() && mapping.IsSourceNullable)
            {
                builder.Append(" ?? ").Append(mapping.NullValue!);
            }
            else if (mapping.RequiresNullCoalescing())
            {
                // A nullable value type source assigned to a non-nullable target must be unwrapped;
                // the null-forgiving operator alone keeps the type nullable (CS0266). Nullable reference
                // types display without "?" in FullyQualifiedFormat, so they correctly keep using "!".
                if (mapping.SourceType.Contains("?") || mapping.SourceType.Contains("Nullable<"))
                {
                    builder.Append(".GetValueOrDefault()");
                }
                else
                {
                    builder.Append("!");
                }
            }
        }
    }

    // The call of the converter method of a mapping with the source value, and the custom parameters when it takes
    // them. A nullable struct goes to a converter taking the struct it holds as its Value, the callers passing a
    // value only. A nullable reference it returns into a target not annotated as nullable is taken with !.
    private static void AppendConverterCall(SourceBuilder builder, PropertyMappingModel mapping, string sourceAccessor, MapperMethodModel method)
    {
        builder.Append(IdentifierHelper.Escape(mapping.ConverterMethod!)).Append("(").Append(sourceAccessor);
        if (mapping.ConverterUnwrapsSource)
        {
            builder.Append(".Value");
        }

        if (mapping.ConverterAcceptsCustomParameters)
        {
            AppendCustomArguments(builder, method, mapping.ConverterParameterRefKinds, 1);
        }

        builder.Append(")");
        if (mapping.ConverterForgivesNull)
        {
            builder.Append("!");
        }
    }

    // Appends a nullable source that needs converting as one expression:
    //   <source> is not null ? <converted> : <fallback>
    // The fallback follows the destination: an explicit NullValue, null for a nullable target,
    // otherwise the target type's default.
    internal static void AppendNullableSourceConversionValue(SourceBuilder builder, PropertyMappingModel mapping, string sourceParamName, MapperMethodModel method, bool nullChecked)
    {
        var sourceAccessor = BuildSourceAccessor(mapping.SourcePath, sourceParamName, nullChecked);
        var isNullableValueType = mapping.SourceType.Contains("?") || mapping.SourceType.Contains("Nullable<");

        builder.Append(sourceAccessor).Append(" is not null ? ");

        if (isNullableValueType)
        {
            BuildTypeConversionWithValueAccess(builder, mapping, sourceAccessor, method);
        }
        else
        {
            BuildTypeConversion(builder, mapping, sourceParamName, nullChecked, method);
        }

        builder.Append(" : ");
        AppendNullFallback(builder, mapping);
    }

    // The value emitted when a null source leaves nothing to convert: an explicit NullValue,
    // null for a nullable target, otherwise the target type's default.
    private static void AppendNullFallback(SourceBuilder builder, PropertyMappingModel mapping)
    {
        if (mapping.HasNullValue())
        {
            builder.Append(mapping.NullValue!);
        }
        else if (mapping.IsTargetNullable)
        {
            builder.Append("null");
        }
        else
        {
            builder.Append("default!");
        }
    }

    internal static void BuildNullableSourceConversion(
        SourceBuilder builder,
        PropertyMappingModel mapping,
        string sourceParamName,
        string target,
        MapperMethodModel method,
        bool nullChecked,
        Action? create = null)
    {
        var sourceAccessor = BuildSourceAccessor(mapping.SourcePath, sourceParamName, nullChecked);

        var isNullableValueType = mapping.SourceType.Contains("?") ||
                                   mapping.SourceType.Contains("Nullable<");

        if (mapping.NullBehavior == NullBehaviorType.Skip)
        {
            builder.Indent().Append("if (").Append(sourceAccessor).Append(" is not null)").NewLine();
            builder.BeginScope();
            create?.Invoke();
            builder.Indent();
            builder.Append(target).Append(" = ");

            if (isNullableValueType)
            {
                BuildTypeConversionWithValueAccess(builder, mapping, sourceAccessor, method);
            }
            else
            {
                BuildTypeConversion(builder, mapping, sourceParamName, nullChecked, method);
            }

            builder.Append(";").NewLine();
            builder.EndScope();
        }
        else
        {
            create?.Invoke();
            builder.Indent();
            builder.Append(target).Append(" = ");
            AppendNullableSourceConversionValue(builder, mapping, sourceParamName, method, nullChecked);
            builder.Append(";").NewLine();
        }
    }

    internal static void BuildTypeConversionWithValueAccess(SourceBuilder builder, PropertyMappingModel mapping, string sourceAccessor, MapperMethodModel method)
    {
        if (mapping.IsEnumMapping())
        {
            // Guarded by the surrounding `is not null` check, so GetValueOrDefault skips the
            // redundant HasValue re-check (and throw path) that .Value would perform.
            var valueAccessor = sourceAccessor + ".GetValueOrDefault()";
            // BuildEnumConversion reads only the enum-conversion members, which this mapping already
            // carries; the copy it used to take here held exactly those same values.
            BuildEnumConversion(builder, mapping, valueAccessor);
            return;
        }

        var converterTypeName = method.MapConverterTypeName ?? Names.QualifiedDefaultValueConverter;

        if (mapping.HasSpecializedConverter())
        {
            if (mapping.HasCulture())
            {
                var formatArg = DetermineFormatArg(mapping);
                builder.Append(converterTypeName)
                       .Append(".")
                       .Append(mapping.SpecializedConverterMethod!)
                       .Append("(")
                       .Append(sourceAccessor)
                       .Append(".GetValueOrDefault(), ")
                       .Append(mapping.CultureArgumentModifier)
                       .Append(GetCultureFieldName(mapping.EffectiveCulture!))
                       .Append(formatArg)
                       .Append(")");
            }
            else
            {
                builder.Append(converterTypeName)
                       .Append(".")
                       .Append(mapping.SpecializedConverterMethod!)
                       .Append("(")
                       .Append(sourceAccessor)
                       .Append(".GetValueOrDefault())");
            }
        }
        else if (mapping.HasParsableMethod())
        {
            var targetTypeForParse = !String.IsNullOrEmpty(mapping.TargetUnderlyingType) ? mapping.TargetUnderlyingType : mapping.TargetType;
            var cultureArg = mapping.HasCulture()
                ? GetCultureFieldName(mapping.EffectiveCulture!)
                : "global::System.Globalization.CultureInfo.InvariantCulture";
            if (mapping.ParseMethod == ParseMethodKind.SpanParsable)
            {
                builder.Append(targetTypeForParse).Append(".Parse(global::System.MemoryExtensions.AsSpan(")
                       .Append(sourceAccessor).Append(".GetValueOrDefault()), ")
                       .Append(cultureArg).Append(")");
            }
            else
            {
                builder.Append(targetTypeForParse).Append(".Parse(")
                       .Append(sourceAccessor).Append(".GetValueOrDefault(), ")
                       .Append(cultureArg).Append(")");
            }
        }
        else if (mapping.RequiresExplicitNumericCast)
        {
            var targetTypeForCast = !String.IsNullOrEmpty(mapping.TargetUnderlyingType) ? mapping.TargetUnderlyingType : mapping.TargetType;
            builder.Append("(").Append(targetTypeForCast).Append(")").Append(sourceAccessor).Append(".GetValueOrDefault()");
        }
        else if (mapping.UserDefinedConversion == UserDefinedConversionKind.Implicit)
        {
            builder.Append(sourceAccessor).Append(".GetValueOrDefault()");
        }
        else if (mapping.HasUserDefinedExplicit())
        {
            var targetTypeForCast = !String.IsNullOrEmpty(mapping.TargetUnderlyingType) ? mapping.TargetUnderlyingType : mapping.TargetType;
            builder.Append("(").Append(targetTypeForCast).Append(")").Append(sourceAccessor).Append(".GetValueOrDefault()");
        }
        else if (mapping.UseFormattable)
        {
            var formatArg = DetermineFormatArg(mapping);
            var cultureArg = mapping.HasCulture()
                ? GetCultureFieldName(mapping.EffectiveCulture!)
                : "global::System.Globalization.CultureInfo.InvariantCulture";
            var formatStr = formatArg.Length > 2 ? formatArg.Substring(2) : "null";
            builder.Append(sourceAccessor).Append(".GetValueOrDefault().ToString(").Append(formatStr).Append(", ").Append(cultureArg).Append(")");
        }
        else
        {
            var converterMethodName = method.MapConverterMethodName;
            var sourceTypeForConversion = !String.IsNullOrEmpty(mapping.SourceUnderlyingType) ? mapping.SourceUnderlyingType : mapping.SourceType;
            var targetTypeForConversion = !String.IsNullOrEmpty(mapping.TargetUnderlyingType) ? mapping.TargetUnderlyingType : mapping.TargetType;

            builder.Append(converterTypeName)
                   .Append(".").Append(IdentifierHelper.Escape(converterMethodName)).Append("<")
                   .Append(sourceTypeForConversion)
                   .Append(", ")
                   .Append(targetTypeForConversion)
                   .Append(">(")
                   .Append(sourceAccessor)
                   .Append(".GetValueOrDefault())");
        }
    }

    internal static string GetNullCheckCondition(PropertyMappingModel mapping, string sourceParamName)
    {
        var conditions = new List<string>();

        var sourceSegmentsArr = mapping.SourcePathSegments;
        if (sourceSegmentsArr.Count > 0)
        {
            var pathBuilder = new StringBuilder();
            pathBuilder.Append(sourceParamName);

            foreach (var segment in sourceSegmentsArr)
            {
                pathBuilder.Append('.').Append(IdentifierHelper.Escape(GetLastName(segment.Path)));
                if (segment.IsNullable)
                {
                    conditions.Add($"{pathBuilder} is not null");
                }
            }
        }

        return String.Join(" && ", conditions);
    }

    internal static string BuildSourceAccessor(string sourcePath, string sourceParamName, bool nullChecked = false)
    {
        if (!sourcePath.Contains('.'))
        {
            return $"{sourceParamName}.{IdentifierHelper.Escape(sourcePath)}";
        }

        var parts = sourcePath.Split('.');
        var result = new StringBuilder();
        result.Append(sourceParamName);

        for (var i = 0; i < parts.Length; i++)
        {
            result.Append('.');
            result.Append(IdentifierHelper.Escape(parts[i]));

            if ((i < parts.Length - 1) && (!nullChecked))
            {
                result.Append('!');
            }
        }

        return result.ToString();
    }

    internal static void BuildTypeConversion(SourceBuilder builder, PropertyMappingModel mapping, string sourceParamName, bool nullChecked, MapperMethodModel method)
    {
        var sourceExpr = BuildSourceAccessor(mapping.SourcePath, sourceParamName, nullChecked);

        if (mapping.IsEnumMapping())
        {
            BuildEnumConversion(builder, mapping, sourceExpr);
            return;
        }

        var converterTypeName = method.MapConverterTypeName ?? Names.QualifiedDefaultValueConverter;

        if (mapping.HasSpecializedConverter())
        {
            if (mapping.HasCulture())
            {
                var formatArg = DetermineFormatArg(mapping);
                builder.Append(converterTypeName)
                       .Append(".")
                       .Append(mapping.SpecializedConverterMethod!)
                       .Append("(")
                       .Append(sourceExpr)
                       .Append(", ")
                       .Append(mapping.CultureArgumentModifier)
                       .Append(GetCultureFieldName(mapping.EffectiveCulture!))
                       .Append(formatArg)
                       .Append(")");
            }
            else
            {
                builder.Append(converterTypeName)
                       .Append(".")
                       .Append(mapping.SpecializedConverterMethod!)
                       .Append("(")
                       .Append(sourceExpr)
                       .Append(")");
            }
        }
        else if (mapping.HasParsableMethod())
        {
            var targetTypeForParse = !String.IsNullOrEmpty(mapping.TargetUnderlyingType) ? mapping.TargetUnderlyingType : mapping.TargetType;
            var cultureArg = mapping.HasCulture()
                ? GetCultureFieldName(mapping.EffectiveCulture!)
                : "global::System.Globalization.CultureInfo.InvariantCulture";
            if (mapping.ParseMethod == ParseMethodKind.SpanParsable)
            {
                builder.Append(targetTypeForParse).Append(".Parse(global::System.MemoryExtensions.AsSpan(")
                       .Append(sourceExpr).Append("), ")
                       .Append(cultureArg).Append(")");
            }
            else
            {
                builder.Append(targetTypeForParse).Append(".Parse(")
                       .Append(sourceExpr).Append(", ")
                       .Append(cultureArg).Append(")");
            }
        }
        else if (mapping.RequiresExplicitNumericCast)
        {
            var targetTypeForCast = !String.IsNullOrEmpty(mapping.TargetUnderlyingType) ? mapping.TargetUnderlyingType : mapping.TargetType;
            builder.Append("(").Append(targetTypeForCast).Append(")").Append(sourceExpr);
        }
        else if (mapping.HasUserDefinedExplicit())
        {
            var targetTypeForCast = !String.IsNullOrEmpty(mapping.TargetUnderlyingType) ? mapping.TargetUnderlyingType : mapping.TargetType;
            builder.Append("(").Append(targetTypeForCast).Append(")").Append(sourceExpr);
        }
        else if (mapping.UseFormattable)
        {
            var formatArg = DetermineFormatArg(mapping);
            var cultureArg = mapping.HasCulture()
                ? GetCultureFieldName(mapping.EffectiveCulture!)
                : "global::System.Globalization.CultureInfo.InvariantCulture";
            var formatStr = formatArg.Length > 2 ? formatArg.Substring(2) : "null";
            builder.Append(sourceExpr).Append(".ToString(").Append(formatStr).Append(", ").Append(cultureArg).Append(")");
        }
        else
        {
            var converterMethodName = method.MapConverterMethodName;
            var sourceTypeForConversion = !String.IsNullOrEmpty(mapping.SourceUnderlyingType) ? mapping.SourceUnderlyingType : mapping.SourceType;
            var targetTypeForConversion = !String.IsNullOrEmpty(mapping.TargetUnderlyingType) ? mapping.TargetUnderlyingType : mapping.TargetType;

            builder.Append(converterTypeName)
                   .Append(".").Append(IdentifierHelper.Escape(converterMethodName)).Append("<")
                   .Append(sourceTypeForConversion)
                   .Append(", ")
                   .Append(targetTypeForConversion)
                   .Append(">(")
                   .Append(sourceExpr)
                   .Append(")");
        }
    }

    internal static string DetermineFormatArg(PropertyMappingModel mapping)
    {
        var isDateTimeFamily = TypeNameHelper.IsDateTimeType(mapping.SourceUnderlyingType) || TypeNameHelper.IsDateTimeType(mapping.TargetUnderlyingType);
        var format = isDateTimeFamily ? mapping.EffectiveDateTimeFormat : mapping.EffectiveNumberFormat;
        return format is null ? ", null" : ", " + ConstantExpressionHelper.FormatString(format);
    }

    internal static void BuildEnumConversion(SourceBuilder builder, PropertyMappingModel mapping, string sourceExpr)
    {
        var targetType = !String.IsNullOrEmpty(mapping.TargetUnderlyingType) ? mapping.TargetUnderlyingType : mapping.TargetType;

        switch (mapping.EnumMappingKind)
        {
            case EnumMappingKind.EnumToEnum:
                builder.Append(sourceExpr).Append(" switch").NewLine();
                builder.Indent().Append("{").NewLine();
                var sourceType = !String.IsNullOrEmpty(mapping.SourceUnderlyingType) ? mapping.SourceUnderlyingType : mapping.SourceType;
                for (var i = 0; i < mapping.SourceEnumMembers.Count; i++)
                {
                    var memberName = mapping.SourceEnumMembers[i];
                    var destIndex = IndexOfEnumMember(mapping.DestEnumMembers, memberName);
                    if (destIndex >= 0)
                    {
                        builder.Indent().Append("    ")
                               .Append(FormatEnumMember(sourceType, memberName, mapping.SourceEnumCastValues, i))
                               .Append(" => ")
                               .Append(FormatEnumMember(targetType, memberName, mapping.DestEnumCastValues, destIndex))
                               .Append(",").NewLine();
                    }
                }
                // A value no member of the target has the name of gives null to a nullable target, and default
                // otherwise
                builder.Indent().Append(mapping.IsTargetNullable ? "    _ => null" : "    _ => default").NewLine();
                builder.Indent().Append("}");
                break;

            case EnumMappingKind.EnumToNumeric:
                builder.Append("(").Append(targetType).Append(")").Append(sourceExpr);
                break;

            case EnumMappingKind.NumericToEnum:
                builder.Append("(").Append(targetType).Append(")").Append(sourceExpr);
                break;

            case EnumMappingKind.EnumToString:
                // Member names are known at compile time; a switch returns cached string constants
                // without the boxing/name-lookup cost of Enum.ToString. Undefined values (e.g. flags
                // combinations) fall back to ToString to preserve semantics.
                if (mapping.SourceEnumMembers.Count > 0)
                {
                    var enumSourceType = !String.IsNullOrEmpty(mapping.SourceUnderlyingType) ? mapping.SourceUnderlyingType : mapping.SourceType;
                    builder.Append(sourceExpr).Append(" switch").NewLine();
                    builder.Indent().Append("{").NewLine();
                    for (var i = 0; i < mapping.SourceEnumMembers.Count; i++)
                    {
                        var memberName = mapping.SourceEnumMembers[i];
                        builder.Indent().Append("    ")
                               .Append(FormatEnumMember(enumSourceType, memberName, mapping.SourceEnumCastValues, i))
                               .Append(" => \"").Append(memberName).Append("\",").NewLine();
                    }
                    builder.Indent().Append("    _ => ").Append(sourceExpr).Append(".ToString()").NewLine();
                    builder.Indent().Append("}");
                }
                else
                {
                    builder.Append(sourceExpr).Append(".ToString()");
                }
                break;

            case EnumMappingKind.StringToEnum:
                // A string switch (length/char dispatch) avoids the Enum.Parse machinery for exact
                // member names; anything else (numeric strings, whitespace, flags lists) falls back
                // to Enum.Parse to preserve semantics. For a nullable target, a string Enum.Parse would
                // throw for gives null instead, as a value of another enum no member has the name of does.
                if (mapping.DestEnumMembers.Count > 0)
                {
                    builder.Append(sourceExpr).Append(" switch").NewLine();
                    builder.Indent().Append("{").NewLine();
                    for (var i = 0; i < mapping.DestEnumMembers.Count; i++)
                    {
                        var memberName = mapping.DestEnumMembers[i];
                        builder.Indent().Append("    \"").Append(memberName).Append("\" => ")
                               .Append(FormatEnumMember(targetType, memberName, mapping.DestEnumCastValues, i))
                               .Append(",").NewLine();
                    }
                    if (mapping.IsTargetNullable)
                    {
                        builder.Indent().Append("    _ => global::System.Enum.TryParse<").Append(targetType).Append(">(").Append(sourceExpr)
                               .Append(", out var __enum) ? __enum : null").NewLine();
                    }
                    else
                    {
                        builder.Indent().Append("    _ => global::System.Enum.Parse<").Append(targetType).Append(">(").Append(sourceExpr).Append(")").NewLine();
                    }
                    builder.Indent().Append("}");
                }
                else
                {
                    builder.Append("global::System.Enum.Parse<").Append(targetType).Append(">(").Append(sourceExpr).Append(")");
                }
                break;
        }
    }

    // A member marked [Obsolete] is written as a cast of its number, as naming it warns (CS0618) or fails (CS0619).
    private static string FormatEnumMember(string enumType, string memberName, EquatableArray<string> castValues, int index) =>
        (index < castValues.Count) && !String.IsNullOrEmpty(castValues[index])
            ? ConstantExpressionHelper.FormatEnumCast(enumType, castValues[index])
            : enumType + "." + IdentifierHelper.Escape(memberName);

    private static int IndexOfEnumMember(EquatableArray<string> members, string memberName)
    {
        for (var i = 0; i < members.Count; i++)
        {
            if (String.Equals(members[i], memberName, StringComparison.Ordinal))
            {
                return i;
            }
        }

        return -1;
    }
